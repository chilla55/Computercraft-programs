-- Install a startup entry for the custom transformer controller.
-- Run: transformer_autostart.lua install [controller-path]
local args = {...}
assert(args[1] == "install" and #args <= 2,
    "Usage: transformer_autostart.lua install [controller-path]")
local controller = "/" .. shell.resolve(args[2] or "transformer.lua"):gsub("^/+", "")
assert(fs.exists(controller) and not fs.isDir(controller), "Missing controller: " .. controller)
assert(not fs.exists("/startup") or fs.isDir("/startup"),
    "/startup is an existing file; preserve that boot script before installing a startup directory")
local path = "/startup/custom_transformer.lua"
local marker = "-- custom-transformer-autostart v1\n"
if fs.exists(path) then
    local previous = assert(fs.open(path, "r")); local text = previous.readAll(); previous.close()
    assert(text:sub(1, #marker) == marker, "Existing startup entry belongs to another program: " .. path)
end
fs.makeDir("/startup")
local out = assert(fs.open(path, "w"), "Cannot write " .. path)
out.write(marker .. "-- Generated by transformer_autostart.lua\n"
    .. "local controller = " .. string.format("%q", controller) .. "\n"
    .. "if not fs.exists(controller) then printError('Missing controller: ' .. controller); return end\n"
    .. "shell.run(controller, 'run')\n")
out.close()
print("Autostart installed: " .. path)
print("Controller: " .. controller)
print("It will run on the next boot. Q exits until the next boot; X pauses automatic retries.")
